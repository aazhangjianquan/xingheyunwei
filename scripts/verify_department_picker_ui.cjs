// All writes stay in the disposable loopback fixture; never point this at a deployed system.
const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path')
const { chromium, request } = require('playwright')
const root = path.resolve(__dirname, '..'), origin = 'http://department-picker.test', apiOrigin = 'http://127.0.0.1:18076'
const password = 'PositionInheritance123!', errors = [], checks = []
const runId = Date.now(), memberUsername = 'dp-' + runId, displayName = '分级选择验证成员' + runId
async function main() {
  const api = await request.newContext({ baseURL: apiOrigin })
  const login = async username => {
    const response = await api.post('/api/login', { data: { username, password } })
    assert.equal(response.status(), 200, await response.text()); return (await response.json()).token
  }
  const token = await login('pi-admin'), headers = { Authorization: 'Bearer ' + token }
  const departments = await (await api.get('/api/departments', { headers })).json()
  const parent = departments.find(d => d.name === '产研中心'), middle = departments.find(d => d.name === '研发中心')
  const child = departments.find(d => d.name === '后端组'), external = departments.find(d => d.name === '其他部门')
  let deep = child
  for (let level = 1; level <= 6; level++) {
    if (departments.some(d => d.name === '平台' + level + '组')) { deep = departments.find(d => d.name === '平台' + level + '组'); continue }
    const response = await api.post('/api/departments', { headers, data: { name: '平台' + level + '组', parent_id: deep.id } })
    assert.equal(response.status(), 200, await response.text()); deep = await response.json()
  }
  const inactive = departments.some(d => d.name === '停用归档组') ? { status: () => 200, text: async () => '' } : await api.post('/api/departments', { headers, data: { name: '停用归档组', active: false } })
  assert.equal(inactive.status(), 200, await inactive.text())
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
  async function open(username = 'pi-admin', options = {}) {
    const page = await browser.newPage({ viewport: options.viewport || { width: 1440, height: 1080 } })
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(value => localStorage.setItem('yunwei_token', value), username === 'pi-admin' ? token : await login(username))
    await page.route('**/*', async route => {
      const url = new URL(route.request().url()); assert.equal(url.origin, origin)
      if (url.pathname.startsWith('/api/')) {
        const response = await route.fetch({ url: apiOrigin + url.pathname + url.search })
        if (url.pathname === '/api/departments' && options.directory) return route.fulfill({ response, json: options.directory(await response.json()) })
        return route.fulfill({ response })
      }
      const file = path.join(root, 'frontend/dist', url.pathname.startsWith('/assets/') ? url.pathname.slice(1) : 'index.html')
      return route.fulfill({ path: file, contentType: file.endsWith('.html') ? 'text/html' : file.endsWith('.js') ? 'text/javascript' : 'text/css' })
    })
    await page.goto(origin + '/users'); return page
  }
  const picker = page => page.getByRole('dialog', { name: '选择所属部门', exact: true })
  const trigger = page => page.getByRole('combobox', { name: '所属部门', exact: true })
  const enter = async (page, name) => picker(page).getByRole('button', { name: name + '，查看下级', exact: true }).click()
  const select = async (page, name) => picker(page).getByRole('button', { name: name + '，选择部门', exact: true }).click()
  const newMember = async page => {
    await page.getByRole('button', { name: /添加成员/ }).first().click()
    await trigger(page).waitFor()
    return page.locator('.member-panel')
  }
  try {
    const page = await open(), modal = await newMember(page)
    let writes = 0
    page.on('request', r => { if (r.method() === 'POST' && new URL(r.url()).pathname === '/api/users') writes++ })
    await modal.getByLabel('用户名 *', { exact: true }).fill(memberUsername)
    await modal.getByLabel('姓名 *', { exact: true }).fill(displayName)
    await modal.locator('input[autocomplete=new-password]').fill(password)
    await modal.getByRole('button', { name: '创建成员', exact: true }).click()
    await picker(page).waitFor()
    assert.equal(writes, 0)
    assert.equal(await trigger(page).getAttribute('aria-invalid'), 'true')
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), '搜索部门')
    checks.push('native required validation blocks submission and focuses the picker')
    assert.equal(await picker(page).locator('.department-option').count(), 2)
    assert.equal(await picker(page).getByRole('button', { name: /后端组/ }).count(), 0)
    assert.equal(await picker(page).getByRole('button', { name: /停用归档组/ }).count(), 0)
    checks.push('initial view contains active visible roots only')
    await enter(page, '产研中心'); await enter(page, '研发中心'); await enter(page, '后端组')
    assert.equal(await picker(page).locator('.department-option').count(), 1)
    await picker(page).getByRole('button', { name: '研发中心', exact: true }).click()
    assert.equal(await picker(page).locator('.department-option').count(), 2)
    await picker(page).getByRole('button', { name: '选择本级', exact: true }).click()
    await picker(page).waitFor({ state: 'hidden' })
    assert.equal(await trigger(page).innerText(), '产研中心 / 研发中心')
    await modal.getByRole('checkbox', { name: /研发协作/ }).waitFor()
    checks.push('drill down, breadcrumb return and parent department selection')
    const position = modal.getByRole('checkbox', { name: /后端开发/ }); await position.check()
    await trigger(page).click()
    assert.equal(await picker(page).locator('.department-option').count(), 2)
    await enter(page, '产研中心')
    await picker(page).getByRole('textbox', { name: '搜索部门', exact: true }).fill('后端组')
    await picker(page).getByText('产研中心 / 研发中心 / 后端组', { exact: true }).waitFor()
    // Search also matches full paths, so descendants of 后端组 are intentionally included.
    assert.ok(await picker(page).locator('.department-option').count() > 1)
    await page.keyboard.press('Escape')
    assert.equal(await position.isChecked(), true)
    assert.equal(await trigger(page).innerText(), '产研中心 / 研发中心')
    assert.equal(await trigger(page).evaluate(el => document.activeElement === el), true)
    checks.push('browsing and cancelling searches preserve the department and selected positions')
    await trigger(page).press('ArrowDown')
    await picker(page).getByRole('textbox', { name: '搜索部门', exact: true }).fill('不存在的部门')
    await picker(page).getByText('未找到匹配部门，试试其他名称', { exact: true }).waitFor()
    await picker(page).getByRole('button', { name: '清空部门搜索', exact: true }).click()
    assert.equal(await picker(page).locator('.department-option').count(), 2)
    await picker(page).getByRole('textbox', { name: '搜索部门', exact: true }).fill('后端组')
    await select(page, '后端组')
    assert.equal(await position.isChecked(), false)
    assert.equal(await trigger(page).innerText(), child.path)
    checks.push('search names and paths, empty state, clear and position reset on confirmed change')
    await position.check(); await trigger(page).click()
    await picker(page).getByRole('textbox', { name: '搜索部门', exact: true }).fill('后端组')
    await select(page, '后端组')
    assert.equal(await position.isChecked(), true)
    checks.push('reselecting the current department preserves position edits')
    await trigger(page).click(); await enter(page, '产研中心'); await enter(page, '研发中心'); await enter(page, '后端组')
    for (let level = 1; level < 6; level++) await enter(page, '平台' + level + '组')
    await page.screenshot({ path: path.join(root, 'reports/department-picker-deep.png'), fullPage: true })
    await select(page, '平台6组')
    assert.ok((await trigger(page).innerText()).endsWith('平台6组'))
    checks.push('nine-level hierarchy navigates to a leaf without flattening')
    await trigger(page).click(); await enter(page, '产研中心'); await enter(page, '研发中心')
    await page.screenshot({ path: path.join(root, 'reports/department-picker-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1)
    const box = await picker(page).boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 844)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    const searchBox = await picker(page).getByRole('textbox', { name: '搜索部门', exact: true }).boundingBox()
    assert.equal(await page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.getAttribute('aria-label'), { x: searchBox.x + 5, y: searchBox.y + 5 }), '搜索部门')
    await page.screenshot({ path: path.join(root, 'reports/department-picker-mobile.png'), fullPage: true })
    checks.push('mobile popover stays inside the viewport and above the scrolling modal')
    await page.keyboard.press('Escape'); await page.setViewportSize({ width: 1440, height: 1080 })
    await trigger(page).click(); await picker(page).getByRole('textbox', { name: '搜索部门', exact: true }).fill('测试组')
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter')
    assert.ok((await trigger(page).innerText()).endsWith('测试组'))
    await trigger(page).click(); await modal.getByLabel('姓名 *', { exact: true }).click()
    await picker(page).waitFor({ state: 'hidden' })
    await trigger(page).click(); await page.keyboard.press('Tab'); await page.keyboard.press('Tab')
    await page.keyboard.press('Escape')
    await trigger(page).click(); await picker(page).getByRole('textbox', { name: '搜索部门', exact: true }).fill('测试组')
    await page.keyboard.press('ArrowUp'); await page.keyboard.press('Enter')
    await picker(page).waitFor({ state: 'hidden' })
    checks.push('keyboard arrows, Enter, Escape and outside-click close')
    await modal.getByRole('button', { name: '创建成员', exact: true }).click()
    await modal.waitFor({ state: 'hidden' }); assert.equal(writes, 1)
    const users = await (await api.get('/api/users', { headers })).json()
    const created = (Array.isArray(users) ? users : users.items).find(u => u.username === memberUsername)
    assert.equal(created.department_id, departments.find(d => d.name === '测试组').id)
    checks.push('created member persists the chosen leaf department')
    // Edit through the other entry point and verify its existing organization payload.
    const row = page.getByRole('row').filter({ hasText: displayName })
    await row.getByRole('button', { name: '调整组织岗位', exact: true }).click()
    const edit = page.getByRole('dialog', { name: /调整组织岗位/ })
    await trigger(page).click(); await enter(page, '产研中心'); await picker(page).getByRole('button', { name: '选择本级', exact: true }).click()
    await edit.getByRole('button', { name: '保存组织岗位', exact: true }).click(); await edit.waitFor({ state: 'hidden' })
    const edited = await (await api.get('/api/users', { headers })).json()
    const saved = (Array.isArray(edited) ? edited : edited.items).find(u => u.username === memberUsername)
    assert.ok(saved.department_ids.includes(parent.id))
    assert.ok(saved.department_ids.includes(created.department_id))
    checks.push('organization edit reuses the picker and preserves existing memberships')
    const head = await open('pi-head')
    await head.getByRole('row').filter({ hasText: '后端成员' }).getByRole('button', { name: '调整组织岗位', exact: true }).click()
    assert.equal(await trigger(head).isDisabled(), true)
    assert.ok((await trigger(head).innerText()).endsWith('后端组'))
    assert.equal(await picker(head).count(), 0)
    checks.push('department head retains the original restricted department directory')
    const historical = await open('pi-admin', { directory: rows => rows.map(d => d.id === parent.id ? { ...d, active: false } : d) })
    await historical.getByRole('row').filter({ hasText: '系统管理员' }).getByRole('button', { name: '调整组织岗位', exact: true }).click()
    assert.ok((await trigger(historical).innerText()).includes('已停用'))
    await trigger(historical).click(); await picker(historical).getByRole('button', { name: '产研中心（已停用），查看下级', exact: true }).click()
    assert.equal(await picker(historical).getByRole('button', { name: '选择本级', exact: true }).isDisabled(), true)
    await picker(historical).getByRole('textbox', { name: '搜索部门', exact: true }).fill('产研中心')
    assert.equal(await picker(historical).getByRole('button', { name: '产研中心（已停用），选择部门', exact: true }).isDisabled(), true)
    checks.push('historical inactive department remains visible but cannot be selected')
    const restricted = await open('pi-admin', { directory: rows => rows.filter(d => [child.id, external.id].includes(d.id)).map(d => ({ ...d, name: '同名部门' })) })
    await newMember(restricted); await trigger(restricted).click()
    assert.equal(await picker(restricted).locator('.department-option').count(), 2)
    await picker(restricted).getByRole('textbox', { name: '搜索部门', exact: true }).fill('同名部门')
    await picker(restricted).getByText(child.path, { exact: true }).waitFor()
    await picker(restricted).getByText(external.path, { exact: true }).waitFor()
    checks.push('missing invisible parents become visible roots and full paths distinguish equal names')
    const empty = await open('pi-admin', { directory: () => [] })
    await newMember(empty); await trigger(empty).click()
    await picker(empty).getByText('暂无可选部门，请联系管理员创建', { exact: true }).waitFor()
    checks.push('empty directory remains usable without fabricating departments')
    assert.deepEqual(errors, [])
    const report = { result: 'passed', checks: checks.length, cases: checks, errors }
    fs.writeFileSync(path.join(root, 'reports/department-picker-ui.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report))
  } finally { await browser.close(); await api.dispose() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
