// Built frontend + isolated SQLite API. Only use with the dedicated fixture server.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium, request } = require('playwright')
const root = path.resolve(__dirname,'..'), origin='http://organization-ui.test'
const apiOrigin=process.env.ORGANIZATION_TEST_API || 'http://127.0.0.1:18069'
const password='Organization123!', errors=[]
const run=Date.now().toString().slice(-8), departmentName='业务一部 · '+run, headUser='org-ui-head-'+run, employeeUser='org-ui-employee-'+run
async function main(){
  const api=await request.newContext({baseURL:apiOrigin})
  const login=async username=>{
    const response=await api.post('/api/login',{data:{username,password}})
    assert.equal(response.status(),200,await response.text())
    return (await response.json()).token
  }
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'})
  async function open(username){
    const token=await login(username)
    const page=await browser.newPage({viewport:{width:1440,height:1080}})
    page.on('pageerror',e=>errors.push(e.message))
    await page.addInitScript(t=>localStorage.setItem('yunwei_token',t),token)
    await page.route('**/*',async route=>{
      const url=new URL(route.request().url())
      assert.equal(url.origin,origin,'UI must not access external services')
      if(url.pathname.startsWith('/api/')){
        const response=await route.fetch({url:apiOrigin+url.pathname+url.search})
        return route.fulfill({response})
      }
      const file=path.join(root,'frontend/dist',url.pathname.startsWith('/assets/')?url.pathname.slice(1):'index.html')
      return route.fulfill({path:file,contentType:file.endsWith('.html')?'text/html':file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':'image/svg+xml'})
    })
    await page.goto(origin+'/users')
    return page
  }
  try{
    const page=await open('org-ui-admin')
    assert.equal(await page.getByText('部门与职责联动',{exact:true}).count(),0)
    await page.getByRole('button',{name:'部门管理',exact:true}).click()
    await page.getByRole('button',{name:'＋ 新建部门',exact:true}).click()
    let dialog=page.getByRole('dialog')
    await dialog.getByLabel('部门名称 *').fill(departmentName)
    await dialog.getByRole('button',{name:'保存',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    for(const name of ['销售','售前']){
      await page.getByRole('tab',{name:/岗位/}).click()
      await page.getByRole('button',{name:'＋ 添加岗位',exact:true}).click()
      dialog=page.getByRole('dialog')
      await dialog.getByLabel('岗位名称 *').fill(name)
      await dialog.getByLabel('销售/售前',{exact:true}).check()
      await dialog.getByRole('button',{name:'保存',exact:true}).click()
      await dialog.waitFor({state:'hidden'})
    }
    for(const [username,name] of [[headUser,'部门负责人甲'],[employeeUser,'业务成员乙']]){
      await page.getByRole('tab',{name:/成员/}).click()
      await page.locator('.org-section-heading').getByRole('button',{name:'＋ 新建成员',exact:true}).click()
      const modal=page.locator('.member-panel')
      assert.equal(await modal.locator('.role-card').filter({hasText:/商业化负责人|项目经理负责人|技术负责人|智能体开发负责人|部门负责人/}).count(),0)
      await modal.getByLabel('用户名 *',{exact:true}).fill(username)
      await modal.getByLabel('姓名 *',{exact:true}).fill(name)
      assert.equal(await modal.locator('select').first().inputValue().then(Number)>0,true)
      await modal.locator('input[autocomplete=new-password]').fill(password)
      await modal.getByRole('button',{name:'创建成员',exact:true}).click()
      await modal.waitFor({state:'hidden'})
      await page.locator('.org-tree button').filter({hasText:departmentName}).click()
    }
    await page.getByRole('button',{name:'设置负责人',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByLabel('部门负责人甲',{exact:true}).check()
    await dialog.getByRole('button',{name:'保存',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await page.getByRole('tab',{name:/岗位/}).click()
    assert.equal(await page.locator('.org-position-list article').count(),2)
    await page.screenshot({path:path.join(root,'reports/organization-admin-desktop.png'),fullPage:true})
    const head=await open(headUser)
    await head.getByRole('button',{name:'部门管理',exact:true}).click()
    await head.locator('.org-tree button').first().waitFor()
    assert.equal(await head.locator('.org-tree button').count(),1)
    assert.equal(await head.getByRole('button',{name:'＋ 新建部门',exact:true}).count(),0)
    const row=head.getByRole('row').filter({hasText:'业务成员乙'})
    await row.getByRole('button',{name:'调整组织岗位',exact:true}).click()
    dialog=head.getByRole('dialog')
    assert.equal(await dialog.getByLabel('所属部门',{exact:true}).isDisabled(),true)
    await dialog.getByLabel('销售',{exact:true}).check()
    await dialog.getByRole('button',{name:'保存组织岗位',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await row.getByText('销售',{exact:true}).waitFor()
    await row.getByRole('button',{name:'调整组织岗位',exact:true}).click()
    dialog=head.getByRole('dialog')
    await dialog.getByLabel('销售',{exact:true}).uncheck()
    await dialog.getByLabel('售前',{exact:true}).check()
    await dialog.getByRole('button',{name:'保存组织岗位',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await row.getByText('售前',{exact:true}).waitFor()
    await head.screenshot({path:path.join(root,'reports/organization-head-desktop.png'),fullPage:true})
    await head.setViewportSize({width:390,height:844})
    await head.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1)
    await head.screenshot({path:path.join(root,'reports/organization-head-mobile.png'),fullPage:true})
    const overflow=await head.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,elements:[...document.querySelectorAll('body *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1 && e.getBoundingClientRect().width>0).map(e=>({tag:e.tagName,cls:e.className,right:e.getBoundingClientRect().right,width:e.getBoundingClientRect().width})).slice(0,15)}))
    assert.ok(overflow.scroll<=overflow.width,JSON.stringify(overflow))
    // Multi-department addition exercises the actual admin dialog against isolated data.
    const adminToken=await login('org-ui-admin'), headers={Authorization:'Bearer '+adminToken}
    async function call(method,url,data){const r=await api[method]('/api'+url,{headers,...(data?{data}:{})});assert.ok(r.ok(),await r.text());return r.json()}
    const sourceDept=await call('post','/departments',{name:'调出部门 · '+run})
    const oldPosition=await call('post',`/departments/${sourceDept.id}/positions`,{name:'原岗位',roles:['tester']})
    const transferred=await call('post','/users',{username:'org-ui-transfer-'+run,display_name:'待调入成员',department_id:sourceDept.id,position_ids:[oldPosition.id],roles:['applicant','project_manager'],password})
    const appointed=await call('put',`/departments/${sourceDept.id}/managers`,{user_ids:[transferred.id],revision:sourceDept.revision})
    assert.ok(appointed.head_ids.includes(transferred.id))
    const project=await call('post','/projects',{name:'保留项目关系 · '+run,department_id:sourceDept.id,members:[{user_id:transferred.id,role:'project_manager'}]})
    await page.getByRole('tab',{name:/成员/}).click()
    await page.getByRole('button',{name:'＋ 添加已有成员',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByLabel('搜索已有成员',{exact:true}).fill('待调入成员')
    await dialog.getByLabel('选择已有成员 *').selectOption(String(transferred.id))
    await dialog.getByLabel('销售',{exact:true}).check()
    await dialog.getByRole('button',{name:'加入并保存',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await page.getByRole('row').filter({hasText:'待调入成员'}).waitFor()
    const people=await call('get','/users'), moved=people.find(p=>p.id===transferred.id)
    assert.equal(moved.department,sourceDept.name)
    assert.equal(moved.department_ids.length,2)
    assert.deepEqual(moved.direct_roles.sort(),['applicant','project_manager'])
    assert.deepEqual(moved.positions.map(p=>p.name).sort(),['原岗位','销售'])
    assert.equal(moved.is_department_manager,true)
    const oldDept=(await call('get','/departments')).find(d=>d.id===sourceDept.id)
    assert.deepEqual(oldDept.head_ids,[transferred.id])
    const retained=(await call('get','/projects')).find(p=>p.id===project.id)
    assert.ok(retained.members.some(m=>m.user_id===transferred.id && m.role==='project_manager'))
    assert.equal(await head.getByRole('button',{name:'＋ 添加已有成员',exact:true}).count(),0)
    const targetDept=(await call('get','/departments')).find(d=>d.name===departmentName)
    const parent=await call('post','/departments',{name:'汇总中心 · '+run})
    for(const child of [oldDept,targetDept]) await call('patch',`/departments/${child.id}`,{name:child.name,parent_id:parent.id,revision:child.revision})
    const directory=await call('get','/departments'), total=directory.find(d=>d.id===parent.id)
    assert.equal(total.direct_member_count,0)
    assert.equal(total.member_count,3,'Shared member must be counted once across children')
    await page.reload()
    await page.getByRole('button',{name:'部门管理',exact:true}).click()
    await page.locator('.org-tree button').filter({hasText:parent.name}).click()
    await page.getByText('直属 0 人 · 含下级共 3 人（去重）',{exact:true}).waitFor()
    await page.getByRole('row').filter({hasText:'待调入成员'}).waitFor()
    assert.equal(await page.getByRole('row').filter({hasText:'待调入成员'}).count(),1)
    await page.screenshot({path:path.join(root,'reports/organization-multi-root-desktop.png'),fullPage:true})
    await page.setViewportSize({width:390,height:844})
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    await page.screenshot({path:path.join(root,'reports/organization-multi-root-mobile.png'),fullPage:true})
    await page.setViewportSize({width:1440,height:1080})
    await page.locator('.org-tree button').filter({hasText:departmentName}).click()
    await page.getByRole('row').filter({hasText:'待调入成员'}).getByRole('button',{name:'调整组织岗位',exact:true}).click()
    dialog=page.getByRole('dialog')
    assert.equal(await dialog.getByLabel('销售',{exact:true}).isChecked(),true)
    assert.equal(await dialog.getByRole('checkbox').count(),2)
    assert.equal(await dialog.getByText(/默认审批部门|主部门/).count(),0)
    await dialog.getByRole('button',{name:'保存组织岗位',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    const finalMember=(await call('get','/users')).find(p=>p.id===transferred.id)
    assert.equal(finalMember.department_id,sourceDept.id)
    assert.deepEqual(finalMember.positions.map(p=>p.name).sort(),['原岗位','销售'])
    assert.deepEqual(finalMember.managed_department_ids,[sourceDept.id])
    const secondaryHead=await open(transferred.username)
    await secondaryHead.getByRole('button',{name:'部门管理',exact:true}).click()
    await secondaryHead.locator('.org-tree button').first().waitFor()
    assert.equal(await secondaryHead.locator('.org-tree button').count(),1)
    assert.ok((await secondaryHead.locator('.org-tree button').first().innerText()).includes(sourceDept.name))
    // Every membership can be removed explicitly, including the original department.
    await page.getByRole('row').filter({hasText:'待调入成员'}).getByRole('button',{name:'调整组织岗位',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByLabel('所属部门',{exact:true}).selectOption(String(sourceDept.id))
    await dialog.getByRole('button',{name:'移出该部门',exact:true}).click()
    await dialog.getByRole('button',{name:'确认移出该部门',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    const removed=(await call('get','/users')).find(p=>p.id===transferred.id)
    assert.deepEqual(removed.department_ids,[targetDept.id])
    assert.deepEqual(removed.positions.map(p=>p.name),['销售'])
    assert.deepEqual(removed.managed_department_ids,[])
    assert.deepEqual(removed.direct_roles.sort(),['applicant','project_manager'])
    assert.ok((await call('get','/projects')).find(p=>p.id===project.id).members.some(m=>m.user_id===transferred.id))
    // Delete only temporary, unused fixture configuration through the actual UI.
    assert.equal(await page.locator('.org-username').filter({hasText:'（主）'}).count(),0)
    assert.equal(await page.getByText(/默认审批部门|主部门/).count(),0)
    assert.equal(await secondaryHead.getByRole('button',{name:'删除部门',exact:true}).count(),0)
    await page.getByRole('button',{name:'＋ 新建部门',exact:true}).click()
    dialog=page.getByRole('dialog')
    const deleteName='删除验收部门 · '+run
    await dialog.getByLabel('部门名称 *').fill(deleteName)
    await dialog.getByRole('button',{name:'保存',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await page.getByRole('tab',{name:/岗位/}).click()
    await page.getByRole('button',{name:'＋ 添加岗位',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByLabel('岗位名称 *').fill('删除验收岗位')
    await dialog.getByLabel('销售/售前',{exact:true}).check()
    await dialog.getByRole('button',{name:'保存',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await page.getByRole('button',{name:'删除部门',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByText('部门岗位：1 项',{exact:true}).waitFor()
    assert.equal(await dialog.getByRole('button',{name:'确认删除部门',exact:true}).isDisabled(),true)
    await page.screenshot({path:path.join(root,'reports/organization-delete-blocked.png'),fullPage:true})
    await dialog.getByRole('button',{name:'取消',exact:true}).click()
    await page.getByRole('button',{name:'删除岗位',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByText('此岗位没有阻止删除的关联。确认后将删除岗位配置，操作记录会保留。',{exact:true}).waitFor()
    await dialog.getByRole('button',{name:'确认删除岗位',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await page.getByText('暂无岗位，可添加「销售」「售前」等岗位。',{exact:true}).waitFor()
    await page.getByRole('button',{name:'删除部门',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByText('此部门没有阻止删除的关联。确认后将删除部门配置，操作记录会保留。',{exact:true}).waitFor()
    await dialog.getByRole('button',{name:'确认删除部门',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await page.locator('.org-tree button').filter({hasText:deleteName}).waitFor({state:'hidden'})
    assert.equal(await page.locator('.org-tree button').filter({hasText:deleteName}).count(),0)
    const employee=await open(employeeUser)
    await employee.getByRole('heading',{name:'用户与权限',exact:true}).waitFor()
    assert.equal(await employee.locator('.sidebar').getByRole('button',{name:'用户与权限',exact:true}).count(),0)
    const token=await login(employeeUser)
    const identity=await api.get('/api/me',{headers:{Authorization:'Bearer '+token}})
    assert.equal((await identity.json()).positions[0].name,'售前')
    assert.deepEqual(errors,[])
    fs.writeFileSync(path.join(root,'reports/organization-ui-verification.json'),JSON.stringify({status:'passed',scope:'built Vue + isolated SQLite API',checks:['empty department','separate sales/presales positions','directory-only member creation','explicit head appointment','head local scope','head position assignment/replacement','ordinary member access','390px layout','retired panel and role options absent','member joins two departments','retained direct roles and project membership','preserved former appointment and position','parent distinct subtree count','parent subtree member list','position editing preserves all department roles','secondary department manager scope','no primary or approval department setting','admin removes original department preserving other roles','admin position deletion','admin empty department deletion','associated department deletion blocked','no deletion control for managers'],pageErrors:errors},null,2))
    console.log('Organization UI: checks passed, no browser errors')
  }finally{await browser.close();await api.dispose()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
