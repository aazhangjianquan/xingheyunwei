// Only the dedicated loopback fixture is permitted; no production data writes.
const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path')
const { chromium, request } = require('playwright')
const root = path.resolve(__dirname, '..'), origin = 'http://position-inheritance.test', apiOrigin = 'http://127.0.0.1:18076'
const password = 'PositionInheritance123!', errors = []
async function main() {
  const api = await request.newContext({baseURL:apiOrigin})
  const login = async username => {const r=await api.post('/api/login',{data:{username,password}});assert.equal(r.status(),200,await r.text());return (await r.json()).token}
  const browser = await chromium.launch({headless:true, executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'})
  async function open(username) {
    const page = await browser.newPage({viewport:{width:1440,height:1080}})
    page.on('pageerror', error=>errors.push(error.message))
    await page.addInitScript(token=>localStorage.setItem('yunwei_token',token),await login(username))
    await page.route('**/*', async route=>{
      const url = new URL(route.request().url());assert.equal(url.origin,origin)
      if(url.pathname.startsWith('/api/'))return route.fulfill({response:await route.fetch({url:apiOrigin+url.pathname+url.search})})
      const file=path.join(root,'frontend/dist',url.pathname.startsWith('/assets/')?url.pathname.slice(1):'index.html')
      return route.fulfill({path:file,contentType:file.endsWith('.html')?'text/html':file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':'image/svg+xml'})
    })
    await page.goto(origin+'/users');await page.getByRole('button',{name:'部门管理',exact:true}).click();return page
  }
  try {
    const page=await open('pi-admin')
    const choose=async name=>{await page.locator('.org-tree button').filter({hasText:name}).click()}
    await choose('后端组');await page.getByRole('tab',{name:/岗位/}).click()
    const cards=page.locator('.org-position-list article')
    assert.equal(await cards.count(),3)
    const inherited=cards.filter({hasText:'后端开发'})
    await inherited.getByText('来自产研中心',{exact:true}).waitFor()
    assert.equal(await inherited.getByRole('button',{name:'编辑岗位'}).count(),0)
    await inherited.getByRole('button',{name:'前往来源部门',exact:true}).click()
    await cards.filter({hasText:'后端开发'}).getByRole('button',{name:'编辑岗位',exact:true}).waitFor()
    await choose('后端组');await page.getByRole('button',{name:'＋ 添加岗位',exact:true}).click()
    let dialog=page.getByRole('dialog')
    await dialog.getByLabel('岗位名称 *').fill('后端开发')
    await dialog.getByRole('button',{name:'保存',exact:true}).click()
    await dialog.getByRole('alert').getByText(/产研中心.*直接引用/).waitFor()
    assert.equal(await dialog.getByLabel('岗位名称 *').inputValue(),'后端开发')
    await dialog.getByRole('button',{name:'取消',exact:true}).click()
    await page.screenshot({path:path.join(root,'reports/position-inheritance-desktop.png'),fullPage:true})
    await page.setViewportSize({width:390,height:844})
    await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1)
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
    await page.screenshot({path:path.join(root,'reports/position-inheritance-mobile.png'),fullPage:true})
    await page.setViewportSize({width:1440,height:1080})
    await page.getByRole('tab',{name:/成员/}).click()
    await page.getByRole('button',{name:'＋ 新建成员',exact:true}).click()
    const modal=page.locator('.member-panel')
    await modal.getByLabel('用户名 *',{exact:true}).fill('pi-new')
    await modal.getByLabel('姓名 *',{exact:true}).fill('新建继承岗位成员')
    await modal.locator('input[autocomplete=new-password]').fill(password)
    await modal.getByRole('checkbox',{name:/后端开发.*来自产研中心/}).check()
    await modal.getByRole('button',{name:'创建成员',exact:true}).click();await modal.waitFor({state:'hidden'})
    await choose('后端组')
    await page.getByRole('button',{name:'＋ 添加已有成员',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByLabel('搜索已有成员',{exact:true}).fill('跨部门成员')
    const options=dialog.getByLabel('选择已有成员 *')
    const id=await options.locator('option').filter({hasText:'跨部门成员'}).getAttribute('value')
    await options.selectOption(id)
    await dialog.getByRole('checkbox',{name:/后端开发.*来自产研中心/}).check()
    await dialog.getByRole('button',{name:'加入并保存',exact:true}).click();await dialog.waitFor({state:'hidden'})
    await page.getByRole('row').filter({hasText:'跨部门成员'}).getByText(/来自产研中心/).waitFor()
    const head=await open('pi-head')
    assert.equal(await head.locator('.org-tree button').count(),1)
    const row=head.getByRole('row').filter({hasText:'后端成员'})
    await row.getByRole('button',{name:'调整组织岗位',exact:true}).click()
    dialog=head.getByRole('dialog')
    assert.equal(await dialog.getByRole('checkbox',{name:/统一运维/}).isDisabled(),true)
    await dialog.getByRole('checkbox',{name:/后端开发.*来自产研中心/}).check()
    await dialog.getByRole('button',{name:'保存组织岗位',exact:true}).click();await dialog.waitFor({state:'hidden'})
    await row.getByText(/后端开发.*来自产研中心/).waitFor()
    await row.getByRole('button',{name:'调整组织岗位',exact:true}).click()
    dialog=head.getByRole('dialog')
    assert.equal(await dialog.getByRole('checkbox',{name:/后端开发.*来自产研中心/}).isChecked(),true)
    await dialog.getByRole('button',{name:'取消',exact:true}).click()
    assert.deepEqual(errors,[])
    const report={checks:10,result:'passed',errors}
    fs.writeFileSync(path.join(root,'reports/position-inheritance-ui.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report))
  } finally {await browser.close();await api.dispose()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
