// Read-only smoke check for the local Compose deployment; no member/department writes.
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), cp = require('node:child_process')
const { chromium } = require('playwright'), root = path.resolve(__dirname, '..')
const code = "from app.database import SessionLocal; from app.models import User; from app.roles import has_role; from app.security import make_token; from sqlalchemy import select; db=SessionLocal(); user=next(u for u in db.scalars(select(User).where(User.active==True)) if has_role(u,'admin')); print(make_token(user.id))"
async function main() {
  const token = cp.execFileSync('docker', ['compose', 'exec', '-T', '--index', '1', 'api', 'python', '-c', code], { cwd: root, encoding: 'utf8' }).trim()
  const errors = [], writes = [], checks = []
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => { if (['POST','PUT','PATCH','DELETE'].includes(r.method()) && new URL(r.url()).pathname.startsWith('/api/')) writes.push(r.method() + ' ' + new URL(r.url()).pathname) })
    await page.addInitScript(value => localStorage.setItem('yunwei_token', value), token)
    await page.goto('http://localhost:8080/users')
    await page.getByRole('button', { name: /添加成员/ }).first().click()
    const trigger = page.getByRole('combobox', { name: '所属部门', exact: true })
    const panel = page.getByRole('dialog', { name: '选择所属部门', exact: true })
    await trigger.click(); await panel.waitFor()
    const departments = await page.evaluate(async () => (await fetch('/api/departments', { headers: { Authorization: 'Bearer ' + localStorage.yunwei_token } })).json())
    const active = departments.filter(d => d.active), visibleIds = new Set(active.map(d => d.id))
    const roots = active.filter(d => !visibleIds.has(d.parent_id))
    assert.equal(await panel.locator('.department-option').count(), roots.length)
    checks.push('deployed creation picker opens at the first visible level')
    const branch = roots.find(d => active.some(c => c.parent_id === d.id))
    assert.ok(branch, 'local deployment should contain a department hierarchy')
    await panel.getByRole('button', { name: branch.name + '，查看下级', exact: true }).click()
    assert.equal(await panel.locator('.department-option').count(), active.filter(d => d.parent_id === branch.id).length)
    await panel.getByRole('button', { name: '选择本级', exact: true }).click()
    assert.equal(await trigger.innerText(), branch.path || branch.name)
    checks.push('deployed hierarchy and parent department selection')
    await trigger.click()
    const leaf = active.find(d => d.parent_id && !active.some(c => c.parent_id === d.id))
    assert.ok(leaf)
    await panel.getByRole('textbox', { name: '搜索部门', exact: true }).fill(leaf.name)
    await panel.getByText(leaf.path, { exact: true }).waitFor()
    await page.screenshot({ path: path.join(root, 'reports/department-picker-deployed-desktop.png'), fullPage: true })
    await panel.getByRole('button', { name: leaf.name + '，选择部门', exact: true }).click()
    assert.equal(await trigger.innerText(), leaf.path)
    checks.push('deployed search displays full paths and chooses the leaf')
    await trigger.click(); await page.setViewportSize({ width: 390, height: 844 })
    await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1)
    const box = await panel.boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 844)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: path.join(root, 'reports/department-picker-deployed-mobile.png'), fullPage: true })
    await page.keyboard.press('Escape'); await panel.waitFor({ state: 'hidden' })
    checks.push('deployed mobile viewport and Escape close')
    await page.locator('.member-panel .modal-head .icon-button').click()
    await page.setViewportSize({ width: 1440, height: 1080 })
    await page.getByRole('button', { name: '调整组织岗位', exact: true }).first().click()
    await trigger.click(); await panel.waitFor()
    assert.equal(await panel.locator('.department-option').count(), roots.length)
    await page.keyboard.press('Escape')
    await page.getByRole('dialog', { name: /调整组织岗位/ }).getByRole('button', { name: '取消', exact: true }).click()
    checks.push('deployed organization editor uses the same hierarchy')
    assert.deepEqual(errors, []); assert.deepEqual(writes, [])
    const report = { result: 'passed', checks: checks.length, cases: checks, url: 'http://localhost:8080', writes, errors }
    fs.writeFileSync(path.join(root, 'reports/department-picker-deployed-ui.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
